defmodule Mix.Tasks.Mondek.Openapi do
  use Mix.Task
  @shortdoc "Generate or check the complete HTTP contract without starting services"
  def run(args) do
    Mix.Task.run("compile")
    spec = MondekWeb.API.ApiSpec.spec()

    routes =
      Enum.filter(
        MondekWeb.Router.__routes__(),
        &(String.starts_with?(&1.path, "/api/v1/") and &1.plug != MondekWeb.API.SpecController)
      )

    declared_ids =
      Enum.map(routes, fn route -> route.plug.open_api_operation(route.plug_opts).operationId end)

    unless length(declared_ids) == length(Enum.uniq(declared_ids)),
      do: Mix.raise("Duplicate declared operation IDs")

    valid_ids? =
      Enum.all?(declared_ids, &(is_binary(&1) and Regex.match?(~r/^[a-zA-Z_][a-zA-Z0-9_]*$/, &1)))

    unless valid_ids?, do: Mix.raise("Operation IDs must be explicit stable identifiers")

    expected = MapSet.new(routes, &{&1.verb, Regex.replace(~r/:([a-z_]+)/, &1.path, "{\\1}")})

    operations =
      for {path, item} <- spec.paths,
          {verb, %OpenApiSpex.Operation{} = operation} <- Map.from_struct(item),
          do: {verb, path, operation}

    actual = MapSet.new(operations, fn {verb, path, _} -> {verb, path} end)
    unless actual == expected, do: Mix.raise("HTTP routes and OpenAPI operations differ")
    ids = Enum.map(operations, fn {_, _, operation} -> operation.operationId end)
    unless length(ids) == length(Enum.uniq(ids)), do: Mix.raise("Duplicate operation IDs")
    data = OpenApiSpex.OpenApi.to_map(spec, vendor_extensions: false)
    check_refs!(data, Map.keys(spec.components.schemas))
    encoded = Jason.encode!(data, pretty: true) <> "\n"
    # The task runs from the controller Mix project.
    path = Path.expand("../contracts/http/v1/openapi.json")

    route_document =
      "# HTTP route inventory\n\nGenerated by `mondek api-spec`. Every retained JSON operation belongs to the unified `/api/v1` contract. The OpenAPI document endpoint is infrastructure and is excluded from its own operation catalog; `/api/docs`, `/health`, HTML and Git smart HTTP are separate transports.\n\nRunner communication and operator workflows use the same experimental same-release policy. HTTP paths may change together with maintained callers; durable evidence and journal identities do not.\n\n| Method | Current path | Previous path | Controller / operation |\n| --- | --- | --- | --- |\n" <>
        (routes
         |> Enum.sort_by(&{&1.path, &1.verb})
         |> Enum.map_join("\n", fn route ->
           action = route.plug_opts
           old = previous_path(action, route.path)

           "| #{route.verb |> Atom.to_string() |> String.upcase()} | `#{route.path}` | #{old} | `#{route.plug |> Module.split() |> List.last()}.#{action}` |"
         end)) <>
        "\n\nRemoved: `GET /api/v1/health` (use the process probe `/health`). No compatibility aliases remain. New operations include the OpenAPI document, exact result evidence and selected result inspection. The bounded snapshot remains an intentional operator diagnostic used by maintained acceptance clients; it is not a complete inventory export.\n"

    route_path = Path.expand("../docs/API-ROUTES.md")

    if "--check" in args do
      unless File.read(route_path) == {:ok, route_document},
        do: Mix.raise("HTTP route inventory is stale; run mondek api-spec")

      unless File.read(path) == {:ok, encoded},
        do: Mix.raise("OpenAPI is stale; run mondek api-spec")
    else
      File.mkdir_p!(Path.dirname(path))
      File.write!(path, encoded)
      File.write!(route_path, route_document)
    end

    Mix.shell().info(
      "HTTP contract #{if "--check" in args, do: "checked", else: "generated"}: #{length(ids)} operations"
    )
  end

  defp previous_path(action, current) do
    path =
      case action do
        :control -> "/api/v1/control"
        :inventory -> "/api/v1/inventory"
        :observations -> "/api/v1/observations"
        :checks -> "/api/v1/checks"
        :check -> "/api/v1/checks/:id"
        :configuration -> "/api/v1/configuration"
        :assignment_inspection -> "/api/v1/assignments/:id/inspection"
        :save -> "/api/v1/assignments/:id"
        :incidents -> "/api/v1/incidents"
        :incident -> "/api/v1/incidents/:id"
        :acknowledge -> "/api/v1/incidents/:id/acknowledge"
        :monitoring_incidents -> "/api/v1/monitoring-incidents"
        :monitoring_incident -> "/api/v1/monitoring-incidents/:id"
        a when a in [:evidence, :observation, :result_inspection] -> nil
        _ -> current
      end

    cond do
      is_nil(path) -> "New"
      path == current -> "Retained; explicit DTO"
      true -> "`#{path}`"
    end
  end

  defp check_refs!(map, names) when is_map(map) do
    for {key, value} <- map do
      if to_string(key) == "$ref" do
        name = String.replace_prefix(value, "#/components/schemas/", "")
        unless name in names, do: Mix.raise("Unresolved schema reference #{value}")
      else
        check_refs!(value, names)
      end
    end
  end

  defp check_refs!(list, names) when is_list(list), do: Enum.each(list, &check_refs!(&1, names))
  defp check_refs!(_, _), do: :ok
end
